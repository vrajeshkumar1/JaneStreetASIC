"""Assemble every program in programs/ into firmware/programs.py, a module of
plain lists and dicts that MicroPython can import:

    python firmware/make_programs.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
from pasm import assemble  # noqa: E402

# Used by demo.selftest(): r0 = 3 * r1, sent to the RX FIFO, then halt.
SELFTEST = """
        add r0, r1, r1
        add r0, r0, r1
        mov isr, r0
        push
        halt
"""


def build():
    """{name: {"words": [...], "labels": {...}}} for every program."""
    out = {"selftest": assemble(SELFTEST)}
    for name in sorted(os.listdir(os.path.join(ROOT, "programs"))):
        if name.endswith(".s"):
            with open(os.path.join(ROOT, "programs", name)) as f:
                out[name[:-2]] = assemble(f.read())
    return {name: {"words": list(p.words), "labels": dict(p.labels)} for name, p in out.items()}


def main():
    lines = ["# Generated by firmware/make_programs.py from programs/*.s. Do not edit.",
             "PROGRAMS = {"]
    for name, prog in build().items():
        words = ", ".join("0x%08X" % w for w in prog["words"])
        labels = ", ".join("%r: %d" % kv for kv in sorted(prog["labels"].items()))
        lines.append("    %r: {\"words\": [%s],\n        \"labels\": {%s}}," % (name, words, labels))
    lines.append("}")
    with open(os.path.join(HERE, "programs.py"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
